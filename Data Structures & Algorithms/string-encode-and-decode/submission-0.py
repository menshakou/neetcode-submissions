class Solution:

    def encode(self, strs: List[str]) -> str:
        """
        Кодируем список строк в одну строку.
        Формат: для каждой строки s добавляем "длина#s"
        """
        res = []  # список для частей итоговой строки
        
        for s in strs:  # проходим по каждой строке
            res.append(str(len(s)))  # добавляем длину строки как строку (например, "5")
            res.append("#")          # добавляем разделитель
            res.append(s)            # добавляем саму строку
            
        # "".join(res) склеивает все элементы списка в одну строку
        # Например: ["5", "#", "Hello", "5", "#", "World"] -> "5#Hello5#World"
        return "".join(res)

    def decode(self, s: str) -> List[str]:
        """
        Декодируем строку обратно в список строк.
        Алгоритм: ищем #, читаем длину до него, потом берём ровно столько символов после.
        """
        res = []  # список для результата
        i = 0     # текущий индекс, с которого начинаем читать
        
        while i < len(s):  # пока не дошли до конца строки
            j = i  # j будем двигать, пока не найдём #
            
            # Ищем позицию # начиная с i
            while s[j] != '#':
                j += 1
            
            # s[i:j] — это подстрока от i до j (не включая j)
            # Например, если s = "5#Hello", i=0, j=1, то s[0:1] = "5"
            length = int(s[i:j])  # превращаем строку с длиной в число
            
            # i = j + 1 — это позиция сразу после # (начало самой строки)
            i = j + 1
            
            # j = i + length — это позиция конца строки
            j = i + length
            
            # s[i:j] — это подстрока от i до j (не включая j)
            # Например, если s = "5#Hello5#World", i=2, j=7, то s[2:7] = "Hello"
            res.append(s[i:j])
            
            # Перемещаем i на позицию после текущей строки, чтобы читать следующую
            i = j
        
        return res
