class Solution:
    def longestConsecutive(self, nums: List[int]) -> int:
        # Кладём все числа в множество.
        # Поиск элемента в set в среднем занимает O(1).
        # Дубликаты автоматически удаляются.
        num_set = set(nums)

        # Здесь будем хранить максимальную длину последовательности.
        longest = 0

        # Перебираем уникальные числа, а не исходный массив.
        for n in num_set:

            # Если n - 1 отсутствует, значит n — начало последовательности.
            #
            # Например:
            # для n = 3, если 2 есть в set, то 3 не начало;
            # для n = 2, если 1 нет, то 2 — начало.
            if n - 1 not in num_set:

                # Начинаем последовательность с самого числа n.
                length = 1

                # Проверяем, существуют ли следующие числа:
                # n + 1, n + 2, n + 3 и так далее.
                while n + length in num_set:
                    length += 1

                # Сохраняем максимальную длину из найденных.
                longest = max(longest, length)

        # Если nums пустой, longest останется равен 0.
        return longest