class Solution:
    def productExceptSelf(self, nums: List[int]) -> List[int]:
        n = len(nums)
    
        # 1️⃣ СОЗДАЕМ МАССИВ РЕЗУЛЬТАТА
        # Создаем массив той же длины и заполняем единицами [1, 1, 1, 1]
        res = []
        for i in range(n):
            res.append(1)
            
        # --------------------------------------------------
        # 2️⃣ ПРОХОД СЛЕВА НАПРАВО ➡️ (Префиксы)
        # Собираем произведение всех чисел СЛЕВА от текущего
        # --------------------------------------------------
        prefix = 1
        for i in range(n):
            # ⚠️ ВАЖНО: Сначала записываем текущий prefix в ответ.
            # На этом шаге в prefix лежат только числа СЛЕВА от nums[i].
            # Само число nums[i] сюда еще НЕ входит!
            res[i] = prefix
            
            # Только ПОСЛЕ записи добавляем nums[i] в накопитель prefix.
            # Теперь nums[i] станет частью префикса для СЛЕДУЮЩИХ элементов.
            prefix = prefix * nums[i]

        # --------------------------------------------------
        # 3️⃣ ПРОХОД СПРАВА НАЛЕВО ⬅️ (Постфиксы)
        # Собираем произведение всех чисел СПРАВА от текущего
        # и умножаем на уже записанный префикс
        # --------------------------------------------------
        postfix = 1
        i = n - 1  # Начинаем с самого последнего элемента
        
        while i >= 0:
            # ⚠️ ВАЖНО: Умножаем префикс (который уже лежит в res[i]) 
            # на накопитель postfix (числа СПРАВА от nums[i]).
            # Само число nums[i] в postfix еще НЕ входит!
            res[i] = res[i] * postfix
            
            # Только ПОСЛЕ умножения добавляем nums[i] в накопитель postfix.
            # Оно пригодится для элементов, которые стоят ЛЕВЕЕ.
            postfix = postfix * nums[i]
            
            # Шагаем влево на один индекс
            i = i - 1

        return res