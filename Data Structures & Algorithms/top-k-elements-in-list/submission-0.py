class Solution:
    def topKFrequent(self, nums: List[int], k: int) -> List[int]:
        # ============================================
        # ШАГ 1: Считаем, сколько раз встречается каждое число
        # ============================================
        count = {}  # словарь: {число: частота}
        
        # Проходим по каждому числу в массиве
        for n in nums:
            if n in count:      # если число уже есть в словаре
                count[n] += 1   # увеличиваем его счетчик на 1
            else:               # если числа еще нет
                count[n] = 1    # добавляем его с частотой 1
        
        # Пример для nums = [1,2,2,3,3,3]:
        # count = {1: 1, 2: 2, 3: 3}
        #          ↑    ↑    ↑
        #          число 1 встречается 1 раз
        #          число 2 встречается 2 раза
        #          число 3 встречается 3 раза
        
        # ============================================
        # ШАГ 2: Создаем "корзины" по частотам
        # ============================================
        # Максимальная частота не может быть больше len(nums)
        # Поэтому создаем len(nums) + 1 корзин (индексы 0..len(nums))
        freq = []
        for i in range(len(nums) + 1):
            freq.append([])  # добавляем пустую корзину
        
        # freq будет выглядеть так: [[], [], [], [], [], [], []]
        #                              ↑    ↑    ↑    ↑    ↑    ↑    ↑
        #                           индекс 0    1    2    3    4    5    6
        #                           (не используется, частота 0 не бывает)
        
        # ============================================
        # ШАГ 3: Раскладываем числа по корзинам
        # ============================================
        for n in count:          # проходим по всем числам в словаре
            cnt = count[n]       # берем частоту этого числа
            freq[cnt].append(n)  # кладем число в корзину под номером cnt
        
        # Для нашего примера:
        # freq[1] = [1]  (число 1 встречается 1 раз)
        # freq[2] = [2]  (число 2 встречается 2 раза)
        # freq[3] = [3]  (число 3 встречается 3 раза)
        # Визуально:
        # freq = [[], [1], [2], [3], [], [], []]
        
        # ============================================
        # ШАГ 4: Собираем k самых частых чисел
        # ============================================
        res = []  # сюда будем складывать ответ
        
        # Идем от конца к началу (от большей частоты к меньшей)
        # range(6, 0, -1) даст числа: 6, 5, 4, 3, 2, 1
        for i in range(len(freq) - 1, 0, -1):
            for n in freq[i]:     # берем все числа из текущей корзины
                res.append(n)     # добавляем в ответ
                if len(res) == k: # если набрали k элементов
                    return res    # возвращаем ответ сразу
        
        return res  # страховка (по условию задачи мы всегда найдем ответ)