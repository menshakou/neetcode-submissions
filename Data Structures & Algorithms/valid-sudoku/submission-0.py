class Solution:
    def isValidSudoku(self, board: List[List[str]]) -> bool:
        # Для каждой строки будем хранить множество уже встреченных цифр.
        # Например, rows[0] — цифры, которые уже встретились в первой строке.
        rows = defaultdict(set)

        # Для каждого столбца — множество встреченных цифр.
        cols = defaultdict(set)

        # Для каждого квадрата 3 x 3 — своё множество цифр.
        # Ключом будет пара:
        # (номер ряда квадратов, номер столбца квадратов)
        squares = defaultdict(set)

        # Проходим по всем строкам
        for r in range(9):

            # В каждой строке проходим по всем столбцам
            for c in range(9):
                value = board[r][c]

                # "." означает пустую клетку.
                # Пустые клетки не нужно проверять.
                if value == ".":
                    continue

                # Определяем, в каком квадрате 3 x 3 находится клетка.
                #
                # r // 3 определяет ряд квадрата:
                # строки 0-2 -> 0
                # строки 3-5 -> 1
                # строки 6-8 -> 2
                #
                # c // 3 определяет столбец квадрата.
                square = (r // 3, c // 3)

                # Проверяем, не встречалась ли цифра:
                # 1. в этой строке;
                # 2. в этом столбце;
                # 3. в этом квадрате.
                #
                # Если встретилась хотя бы в одном месте,
                # Sudoku недействителен.
                if (
                    value in rows[r]
                    or value in cols[c]
                    or value in squares[square]
                ):
                    return False

                # Если дубликата нет, запоминаем цифру
                # сразу в трёх связанных структурах.
                rows[r].add(value)
                cols[c].add(value)
                squares[square].add(value)

        # Если мы прошли всю доску и не нашли дубликатов,
        # доска является валидной.
        return True
        